export const exportProgressReportPDF = ({
  child, attendanceStats, memoProgress,
  teacherNotes, classN, period, schoolName, country, region, teacherName,
}) => {
  const lang = getCurrentLang();
  const labels = L[lang] || L.en;
  const isAr = lang === 'ar';

  const childName = isAr
    ? (child?.nameAr || child?.name || '')
    : (child?.nameEn || child?.name || '');

  const schoolLine = [schoolName, country, region].filter(Boolean).join(' — ');

  const body = `
    <div class="info-box">
      <div class="main-name">${childName}</div>
      <div class="meta">
        ${labels.class}: ${classN || '—'} &nbsp;|&nbsp; ${labels.period}: ${period || '—'}
        ${teacherName ? `<br>${labels.teacher}: ${teacherName}` : ''}
        ${schoolLine ? `<br>${schoolLine}` : ''}
      </div>
    </div>

    ${attendanceStats ? `
    <div class="section">
      <div class="section-header">${labels.attendance}</div>
      <div class="stats-row">
        <div class="stat-card sc-blue">
          <div class="sv">${attendanceStats.total}</div>
          <div class="sl">${labels.total}</div>
        </div>
        <div class="stat-card sc-green">
          <div class="sv">${attendanceStats.present}</div>
          <div class="sl">${labels.present}</div>
        </div>
        <div class="stat-card sc-red">
          <div class="sv">${attendanceStats.absent}</div>
          <div class="sl">${labels.absent}</div>
        </div>
        <div class="stat-card ${attendanceStats.rate >= 80 ? 'sc-green' : 'sc-gold'}">
          <div class="sv">${attendanceStats.rate}%</div>
          <div class="sl">${labels.rate}</div>
        </div>
      </div>
    </div>` : ''}

    ${memoProgress !== undefined ? `
    <div class="section">
      <div class="section-header">${labels.progress}</div>
      <div class="hizb-box">
        <div class="hv">${(memoProgress || 0).toFixed(2)}</div>
        <div class="hl">${labels.hizb} / 60</div>
        <div class="prog-wrap" style="margin-top:10px">
          <div class="prog-track">
            <div class="prog-fill" style="width:${Math.min(((memoProgress || 0) / 60) * 100, 100).toFixed(1)}%;background:linear-gradient(90deg,#d97706,#fbbf24)"></div>
          </div>
          <span style="font-size:12px;color:#92400e;white-space:nowrap">
            ${(((memoProgress || 0) / 60) * 100).toFixed(1)}%
          </span>
        </div>
      </div>
    </div>` : ''}

    ${teacherNotes ? `
    <div class="section">
      <div class="section-header">${labels.notes}</div>
      <div class="notes-box">${teacherNotes}</div>
    </div>` : ''}
  `;

  openPrintWindow(body, labels.progressReport, lang);
};

