const openPrintWindow = (bodyHtml, reportTitle, lang) => {
  const isAr = lang === 'ar';
  const labels = L[lang] || L.en;
  const today = new Date().toLocaleDateString(isAr ? 'ar-SA-u-ca-islamic' : 'en-US', {
    year: 'numeric', month: 'long', day: 'numeric',
  });

  const html = `<!DOCTYPE html>
<html dir="${isAr ? 'rtl' : 'ltr'}" lang="${lang}">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width,initial-scale=1">
  <title>${reportTitle}</title>
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link href="https://fonts.googleapis.com/css2?family=Amiri:ital,wght@0,400;0,700;1,400&family=Inter:wght@300;400;500;600;700&display=swap" rel="stylesheet">
  <style>${getStyles(isAr)}</style>
</head>
<body>
<div class="page">
  <div class="header">
    <div class="header-brand">
      <div class="name">${labels.appName}</div>
      <div class="sub">${labels.appSub}</div>
    </div>
    <div class="header-report">
      <div class="title">${reportTitle}</div>
    </div>
  </div>
  <div class="gold-bar"></div>
  ${bodyHtml}
  <div class="footer">
    <span>${labels.generatedBy}</span>
    <span>${today}</span>
  </div>
</div>
<script>
  document.fonts.ready.then(function() {
    setTimeout(function() { window.print(); }, 400);
  });
</script>
</body>
</html>`;

  const win = window.open('', '_blank');
  if (!win) {
    alert(lang === 'ar' ? 'يرجى السماح بالنوافذ المنبثقة لتصدير التقارير' : 'Please allow pop-ups to export reports');
    return;
  }
  win.document.write(html);
  win.document.close();
};

const evalBadge = (evaluation, lang) => {
  const labels = L[lang] || L.en;
  const cls = { excellent: 'bg', good: 'bb', average: 'bo', repeat: 'br' };
  const text = labels[`eval_${evaluation}`] || evaluation;
  return `<span class="badge ${cls[evaluation] || 'bb'}">${text}</span>`;
};

