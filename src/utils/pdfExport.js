export const exportMemorizationPDF = ({ title, studentName, classN, records, totalHizb, lang: langProp }) => {
  const lang = langProp || getCurrentLang();
  const labels = L[lang] || L.en;
  const isAr = lang === 'ar';

  const body = `
    ${studentName ? `
    <div class="info-box">
      <div class="main-name">${studentName}</div>
      <div class="meta">
        ${labels.class}: ${classN || '—'}
        &nbsp;|&nbsp;
        ${labels.totalHizb}: <strong>${(totalHizb || 0).toFixed(2)}</strong> ${labels.hizb}
      </div>
    </div>` : ''}

    <div class="section">
      <div class="section-header">${labels.memoReport}</div>
      <table>
        <thead>
          <tr>
            <th>${labels.date}</th>
            <th>${labels.surah}</th>
            <th>${labels.ayahs}</th>
            <th>${labels.evaluation}</th>
          </tr>
        </thead>
        <tbody>
          ${(records || []).map(r => {
            const from = r.fromAyah;
            const to = r.toAyah;
            const count = to - from + 1;
            const range = isAr ? `${to} ← ${from}` : `${from} → ${to}`;
            return `
            <tr>
              <td>${r.date}</td>
              <td>${r.surahName || '—'}</td>
              <td>${range} <span style="color:#94a3b8;font-size:11px">(${count})</span></td>
              <td>${evalBadge(r.evaluation, lang)}</td>
            </tr>`;
          }).join('')}
        </tbody>
      </table>
    </div>
  `;

  openPrintWindow(body, title || labels.memoReport, lang);
};

