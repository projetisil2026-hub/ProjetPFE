export const exportAttendancePDF = ({ title, studentName, classN, period, records, stats, lang: langProp }) => {
  const lang = langProp || getCurrentLang();
  const labels = L[lang] || L.en;

  const body = `
    ${studentName ? `
    <div class="info-box">
      <div class="main-name">${studentName}</div>
      <div class="meta">${labels.class}: ${classN || '—'} &nbsp;|&nbsp; ${labels.period}: ${period || '—'}</div>
    </div>` : ''}

    ${stats ? `
    <div class="stats-row">
      <div class="stat-card sc-blue">
        <div class="sv">${stats.total}</div>
        <div class="sl">${labels.total}</div>
      </div>
      <div class="stat-card sc-green">
        <div class="sv">${stats.present}</div>
        <div class="sl">${labels.present}</div>
      </div>
      <div class="stat-card sc-red">
        <div class="sv">${stats.absent}</div>
        <div class="sl">${labels.absent}</div>
      </div>
      <div class="stat-card ${stats.rate >= 80 ? 'sc-green' : 'sc-gold'}">
        <div class="sv">${stats.rate}%</div>
        <div class="sl">${labels.rate}</div>
      </div>
    </div>` : ''}

    <div class="section">
      <div class="section-header">${labels.attendReport}</div>
      <table>
        <thead>
          <tr>
            <th>${labels.date}</th>
            <th>${labels.name}</th>
            <th>${labels.status}</th>
          </tr>
        </thead>
        <tbody>
          ${(records || []).map(r => `
          <tr>
            <td>${r.date}</td>
            <td>${r.studentName || studentName || '—'}</td>
            <td>
              <span class="badge ${r.status === 'present' ? 'bg' : 'br'}">
                ${r.status === 'present' ? labels.present : labels.absent}
              </span>
            </td>
          </tr>`).join('')}
        </tbody>
      </table>
    </div>
  `;

  openPrintWindow(body, title || labels.attendReport, lang);
};

